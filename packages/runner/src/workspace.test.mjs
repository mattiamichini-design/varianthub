import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, writeFile, readFile, mkdir, symlink, rm, stat } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { createWorkspace, initializeProject, validateLayout } from './workspace.mjs';

test('real project: source truth, atomic saves, conflicts, origins, paths and repeatable init', async () => {
  const root = await mkdtemp(join(tmpdir(), 'varianthub-check-'));
  const outside = await mkdtemp(join(tmpdir(), 'varianthub-outside-'));
  const layout = {version:1,variantOrder:['a','b'],comparedVariantIds:['a'],gridCols:4};
  const config = {projectId:'test-project',roots:['public'],explorations:[{key:'example',sourcePaths:['public/page.html']},{key:'remote'}]};
  const git = (...args) => execFileSync('git',args,{cwd:root,stdio:'pipe'});
  try {
    await mkdir(join(root,'public'));
    await writeFile(join(root,'public/page.html'),'<input aria-label="Name">');
    await writeFile(join(outside,'secret'),'private');
    await symlink(join(outside,'secret'),join(root,'public','leak'));
    const starterRoot = join(root, 'starter');
    await mkdir(starterRoot);
    const starter = await initializeProject(starterRoot, {examples:true});
    assert.equal(starter.explorations.length, 2);
    assert.equal(starter.explorations[0].variants[0].source.type, 'html');
    assert.equal(starter.explorations[1].variants[0].source.type, 'url');
    const starterHtml = join(starterRoot,'varianthub-examples/fieldwork/index.html');
    assert.match(await readFile(starterHtml,'utf8'), /Fieldwork/);
    await writeFile(starterHtml, 'My edited example');
    assert.deepEqual(await initializeProject(starterRoot, {examples:true}), starter);
    assert.equal(await readFile(starterHtml,'utf8'), 'My edited example');
    const initial = await initializeProject(root);
    assert.deepEqual(await initializeProject(root),initial);
    const workspace = await createWorkspace({root,config});
    assert.equal((await workspace.metadata(true)).example.history,'no-git');
    assert.equal((await workspace.load('example')).revision,null);
    await assert.rejects(stat(join(root,'.varianthub')), {code:'ENOENT'});
    const readOnly=await createWorkspace({root,config,allowWrites:false});
    await assert.rejects(readOnly.save('example',null,layout),{status:403});
    git('init'); git('config','user.email','test@example.com'); git('config','user.name','Test');
    assert.equal((await workspace.metadata(true)).example.history,'no-head');
    git('add','public/page.html'); git('commit','-m','Initial page');
    const committed = await workspace.metadata(true);
    assert.match(committed.example.lastCommit,/^\d{4}-/);
    assert.equal(committed.example.localChanges,false);
    assert.equal(committed.remote.history,'unknown');
    await writeFile(join(root,'public/page.html'),'<input aria-label="Changed">');
    assert.equal((await workspace.metadata(true)).example.localChanges,true);
    assert.equal((await workspace.metadata(true)).example.lastCommit,committed.example.lastCommit);
    const nested = await createWorkspace({root:join(root,'public'),config:{projectId:'nested',roots:['.'],explorations:[{key:'page',sourcePaths:['page.html']}]}});
    assert.equal((await nested.metadata(true)).page.localChanges,true);
    assert.equal((await nested.metadata(true)).page.lastCommit,committed.example.lastCommit);
    await assert.rejects(createWorkspace({root,config:{...config,explorations:[{key:'bad',sourcePaths:['../outside']}]}}));
    const saved = await workspace.save('example',null,layout);
    assert.deepEqual((await workspace.load('example')).layout,layout);
    const results = await Promise.allSettled([workspace.save('example',saved.revision,{...layout,gridCols:2}),workspace.save('example',saved.revision,{...layout,gridCols:3})]);
    assert.equal(results.filter(result=>result.status==='fulfilled').length,1);
    assert.equal(results.find(result=>result.status==='rejected').reason.status,409);
    const before = await readFile(join(root,'.varianthub/layouts/example.json'),'utf8');
    await assert.rejects(workspace.save('example',null,layout),{status:409});
    assert.equal(await readFile(join(root,'.varianthub/layouts/example.json'),'utf8'),before);
    await assert.rejects(workspace.asset('../secret'));
    await assert.rejects(workspace.asset('public/leak'),{status:403});
    await assert.rejects(workspace.asset('varianthub.config.json'),{status:403});
    await assert.rejects(workspace.load('../outside'));
    assert.throws(()=>validateLayout({...layout,comparedVariantIds:['missing']}));
    assert.equal(validateLayout({...layout,variantOrder:Array.from({length:20},(_,index)=>`v${index}`),comparedVariantIds:Array.from({length:20},(_,index)=>`v${index}`)}).comparedVariantIds.length,20);
    assert.throws(()=>validateLayout({...layout,variantOrder:Array.from({length:21},(_,index)=>`v${index}`),comparedVariantIds:Array.from({length:21},(_,index)=>`v${index}`)}));
    assert.deepEqual(validateLayout({...layout,variantOrder:['a','b','c'],pendingVariantIds:['c']}).pendingVariantIds,['c']);
    assert.throws(()=>validateLayout({...layout,canvas:{preset:'custom',resizeLocked:false,artboards:{a:{x:0,y:0,width:NaN,height:500}}}}));
    const hostile = await workspace.handle(new Request('http://localhost:3100/api/workspace/example',{method:'PUT',headers:{origin:'https://attacker.test','content-type':'application/json'},body:JSON.stringify({revision:saved.revision,layout})}),'example');
    assert.equal(hostile.status,403);
    const rebound = await workspace.handle(new Request('http://attacker.test/api/workspace'));
    assert.equal(rebound.status,403);
    const fresh = await createWorkspace({root,config});
    assert.deepEqual(await fresh.load('example'),await workspace.load('example'));
    const blockedRoot = join(root,'blocked'); await mkdir(blockedRoot); await symlink(outside,join(blockedRoot,'.varianthub'));
    const blocked = await createWorkspace({root:blockedRoot,config:{...config,roots:['.']}});
    await assert.rejects(blocked.save('example',null,layout),{status:403});
  } finally { await rm(root,{recursive:true,force:true}); await rm(outside,{recursive:true,force:true}); }
});
