test('presets resolve colliding artboards and a custom viewport applies to every visible artboard',async({page,request,baseURL})=>{
  await seed(request,baseURL!,{preset:'mobile',resizeLocked:false,artboards:Object.fromEntries(ids.map((id,index)=>[id,{x:index*100,y:0,width:390,height:844}]))});
  await page.goto('/items/action-surface');
  await expect(page.locator('.vh-save-status')).toHaveAttribute('title','Saved');
  await page.getByRole('button',{name:'Canvas',exact:true}).click();
  const toolbar=page.locator('.vh-canvas-toolbar');
  await toolbar.getByRole('button',{name:'Zoom out',exact:true}).hover();
  const tooltip=toolbar.getByRole('tooltip');
  await expect(tooltip).toHaveText('Zoom out');
  await expect(tooltip).toHaveCSS('opacity','1');
  const bubbleId=await tooltip.getAttribute('id');
  const start=await tooltip.boundingBox();
  await toolbar.getByRole('button',{name:'Zoom in',exact:true}).hover();
  await expect(tooltip).toHaveText('Zoom in');
  await expect(tooltip).toHaveAttribute('id',bubbleId!);
  await expect(tooltip).toHaveCSS('opacity','1');
  await expect.poll(async()=>(await tooltip.boundingBox())!.x).toBeGreaterThan(start!.x);
  await page.keyboard.press('Escape');
  await expect(tooltip).toHaveCSS('opacity','0');
  const viewport=page.getByRole('button',{name:'Viewport',exact:true});
  await viewport.click();
  await page.getByRole('menuitemradio',{name:/^Tablet/}).click();
  await expect.poll(async()=>{
    const boards=(await (await request.get('/api/workspace/action-surface')).json()).layout.canvas.artboards;
    return ids.every((id,index)=>boards[id].width===768 && (index===0 || boards[id].x>=boards[ids[index-1]].x+768));
  }).toBe(true);
  await viewport.click();
  await page.getByRole('menuitemradio',{name:/^Custom/}).click();
  await page.getByRole('spinbutton',{name:'Custom viewport width',exact:true}).fill('610');
  await page.getByRole('spinbutton',{name:'Custom viewport width',exact:true}).press('Enter');
  await page.getByRole('spinbutton',{name:'Custom viewport height',exact:true}).fill('700');
  await page.getByRole('spinbutton',{name:'Custom viewport height',exact:true}).press('Enter');
  await expect(viewport).toContainText('Custom');
  await expect(viewport).toContainText('610 × 700');
  await page.getByRole('button',{name:/Apply.*all/i}).click();
  await expect.poll(async()=>{
    const boards=(await (await request.get('/api/workspace/action-surface')).json()).layout.canvas.artboards;
    return ids.every(id=>boards[id].width===610 && boards[id].height===700);
  }).toBe(true);
  for(let index=0;index<3;index++)await expect.poll(()=>page.frameLocator('.vh-canvas-artboard iframe').nth(index).locator('body').evaluate(()=>[innerWidth,innerHeight])).toEqual([610,700]);
  await page.getByRole('button',{name:'Fit all',exact:true}).click();
  await expect.poll(()=>page.locator('.vh-canvas-artboard').evaluateAll(nodes=>nodes.every(node=>{const r=node.getBoundingClientRect();return r.left>=0 && r.right<=innerWidth;}))).toBe(true);
  await page.screenshot({path:'output/playwright/review-canvas-custom.png'});
});

test('command palette opens from shortcut, searches and navigates without losing keyboard focus',async({page})=>{
  await page.goto('/items/action-surface');
  await page.keyboard.press('Meta+k');
  const dialog=page.getByRole('dialog');
  await expect(dialog).toBeVisible();
  await page.screenshot({path:'output/playwright/review-command-menu.png'});
  const search=dialog.getByLabel('Search explorations',{exact:true});
  const initial=await search.getAttribute('aria-activedescendant');
  await page.keyboard.down('ArrowDown');
  await expect(dialog.locator('kbd').filter({hasText:'↓'})).toHaveAttribute('data-pressed','true');
  await page.keyboard.up('ArrowDown');
  await expect(dialog.locator('kbd').filter({hasText:'↓'})).not.toHaveAttribute('data-pressed','true');
  await expect(search).not.toHaveAttribute('aria-activedescendant',initial!);
  await page.keyboard.down('ArrowUp');
  await expect(dialog.locator('kbd').filter({hasText:'↑'})).toHaveAttribute('data-pressed','true');
  await page.evaluate(()=>window.dispatchEvent(new Event('blur')));
  await expect(dialog.locator('kbd').filter({hasText:'↑'})).not.toHaveAttribute('data-pressed','true');
  await page.keyboard.up('ArrowUp');
  await search.press('ArrowUp');
  await expect(search).toHaveAttribute('aria-activedescendant',initial!);
  await search.fill('information');
  await page.keyboard.press('ArrowDown');
  await page.keyboard.down('Enter');
  await expect(dialog.locator('kbd').filter({hasText:'↵'})).toHaveAttribute('data-pressed','true');
  await expect(dialog).toBeVisible();
  await page.keyboard.up('Enter');
  await expect(page).toHaveURL(/items\/information-card/);
  await expect(dialog).not.toBeVisible();
  await page.keyboard.press('Control+k');
  await expect(dialog).toBeVisible();
  await page.keyboard.down('Escape');
  await expect(dialog.locator('kbd').filter({hasText:'Esc'})).toHaveAttribute('data-pressed','true');
  await expect(dialog).toBeVisible();
  await page.keyboard.up('Escape');
  await expect(dialog).not.toBeVisible();
  await expect(page.locator('.vh-selector-trigger:visible').first()).toBeFocused();
  await page.locator('.vh-selector-trigger:visible').first().click();
  const compact=page.getByRole('dialog',{name:'Choose an exploration'});
  await compact.getByLabel('Search explorations',{exact:true}).fill('information');
  await expect(compact.getByRole('option')).toHaveCount(1);
  await page.getByRole('button',{name:/Open command menu/i}).click();
  await expect(dialog).toBeVisible();
});

test('narrow toolbar stays within its viewport and explains unavailable columns',async({page,request,baseURL})=>{
  await seed(request,baseURL!);
  await page.setViewportSize({width:1775,height:1066});
  await page.goto('/items/action-surface');
  await expect(page.locator('.vh-save-status')).toHaveAttribute('title','Saved');
  await page.locator('button[title="4 columns"]:visible').click();
  await page.setViewportSize({width:680,height:900});
  const four=page.locator('button[title="4 columns"]:visible');
  await expect(four).toBeEnabled();
  await expect(four).toHaveAttribute('aria-pressed','true');
  await expect(page.locator('.vh-card')).toHaveCount(0);
  await expect(page.getByText(/needs more room|widen|resize|wider|available width/i).first()).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(680);
  await page.screenshot({path:'output/playwright/review-toolbar-narrow.png',fullPage:true});
  await page.locator('button[title="1 column"]:visible').click();
  await expect(page.locator('.vh-card')).toHaveCount(3);
  for(const width of [390,680,768,1024,1440]){
    await page.setViewportSize({width,height:844});
    const header=await page.locator('.vh-page-header').boundingBox();
    expect(header!.height).toBeLessThan(200);
    expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
  }
});
