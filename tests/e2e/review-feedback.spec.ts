import {test,expect,type APIRequestContext} from '@playwright/test';

const ids=['slate-quiet','blue-standard','violet-strong'];
async function seed(request:APIRequestContext,baseURL:string,canvas?:object){
  const session=await (await request.get('/api/workspace')).json();
  const current=await (await request.get('/api/workspace/action-surface')).json();
  expect((await request.put('/api/workspace/action-surface',{headers:{Origin:new URL(baseURL).origin,'X-VariantHub-Token':session.token},data:{revision:current.revision,layout:{version:1,variantOrder:ids,comparedVariantIds:ids,gridCols:2,...(canvas?{canvas}:{})}}})).ok()).toBeTruthy();
}

